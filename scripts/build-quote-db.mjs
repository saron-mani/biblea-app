// Builds assets/data/quoteBank.db from src/quoteBank.json.
// Run with: node scripts/build-quote-db.mjs
// Verify with: node scripts/build-quote-db.mjs --check
// The generated .db is committed so EAS builds don't need this script.
// A hash of the source JSON is stored inside the DB and exported to
// src/quoteBank.meta.ts so native clients can detect a stale on-device copy.

import { DatabaseSync } from "node:sqlite";
import { createHash } from "node:crypto";
import {
  existsSync,
  mkdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const source = resolve(root, "src/quoteBank.json");
const out = resolve(root, "assets/data/quoteBank.db");
const metaFile = resolve(root, "src/quoteBank.meta.ts");

const checkOnly = process.argv.includes("--check");
const sourceBytes = readFileSync(source);
const hash = createHash("sha256").update(sourceBytes).digest("hex");
const metaContents = `// Generated by scripts/build-quote-db.mjs. Do not edit.
// SHA-256 of src/quoteBank.json; used to detect stale bundled databases.
export const QUOTE_BANK_SOURCE_HASH = "${hash}";
`;

function fail(message) {
  console.error(message);
  process.exit(1);
}

function readDbHash() {
  const db = new DatabaseSync(out, { readOnly: true });
  try {
    const row = db
      .prepare("SELECT value FROM meta WHERE key = 'source_sha256'")
      .get();
    return row?.value ?? null;
  } catch {
    // Databases built before the meta table existed.
    return null;
  } finally {
    db.close();
  }
}

if (checkOnly) {
  if (!existsSync(out)) fail(`quoteBank.db is missing: ${out}`);

  const dbHash = readDbHash();
  let metaHash = null;
  try {
    metaHash = readFileSync(metaFile, "utf8").match(
      /QUOTE_BANK_SOURCE_HASH = "([a-f0-9]+)"/,
    )?.[1] ?? null;
  } catch {
    // No generated meta module yet.
  }

  if (dbHash === hash && metaHash === hash) {
    console.log(`quoteBank.db is up to date (${hash})`);
    process.exit(0);
  }

  fail(
    "quoteBank.db is stale. Run `node scripts/build-quote-db.mjs`.\n" +
      `  expected: ${hash}\n` +
      `  db:       ${dbHash ?? "<missing>"}\n` +
      `  meta:     ${metaHash ?? "<missing>"}`,
  );
}

const bank = JSON.parse(sourceBytes.toString("utf8"));
mkdirSync(dirname(out), { recursive: true });
rmSync(out, { force: true });

const db = new DatabaseSync(out);
db.exec(`
  PRAGMA journal_mode = DELETE;
  CREATE TABLE verses (
    id INTEGER PRIMARY KEY,
    book TEXT NOT NULL,
    chapter TEXT NOT NULL,
    verse TEXT NOT NULL,
    text TEXT NOT NULL,
    UNIQUE (book, chapter, verse)
  );
  CREATE TABLE meta (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
  );
`);

const insert = db.prepare(
  "INSERT INTO verses (book, chapter, verse, text) VALUES (?, ?, ?, ?)",
);

let count = 0;
db.exec("BEGIN");
for (const [book, chapters] of Object.entries(bank)) {
  for (const [chapter, verses] of Object.entries(chapters)) {
    for (const [verse, text] of Object.entries(verses)) {
      insert.run(book, chapter, verse, text);
      count += 1;
    }
  }
}
db.exec("COMMIT");
db.prepare("INSERT INTO meta (key, value) VALUES (?, ?)").run(
  "source_sha256",
  hash,
);
db.close();

writeFileSync(metaFile, metaContents);
console.log(`Wrote ${count} verses to ${out} (source hash ${hash})`);
